// Config compartida entre auth.js (Node, con Prisma) y middleware.js
// (Edge runtime). No debe importar nada que dependa de Prisma: el
// middleware corre en Edge y Prisma no es compatible con ese runtime.
export const authConfig = {
  session: { strategy: "jwt" },
  pages: { signIn: "/login" },
  providers: [],
  callbacks: {
    jwt({ token, user }) {
      if (user) {
        token.id = user.id;
        token.role = user.role;
      }
      return token;
    },
    session({ session, token }) {
      if (session.user) {
        session.user.id = token.id;
        session.user.role = token.role;
      }
      return session;
    },
  },
};
